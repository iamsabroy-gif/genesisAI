"""
Project Genesis: Person Due Diligence & Educator Verification Engine.
Performs multi-pillar OSINT research to verify tutors, educators, and professionals.
"""

import re
import urllib.parse
import datetime
from typing import Dict, Any, List, Optional

from genesis.config import RESEARCH_DIR
from genesis.tools.web_research import web_search, web_scrape


def person_due_diligence(
    name: str,
    location: str = "",
    affiliation: str = "",
    identifier: str = "",
    save_to_vault: bool = True,
) -> str:
    """
    Perform OSINT due diligence and verification on an individual (tutor, educator, contractor).
    
    Args:
        name: Full name of the person.
        location: City, state, or neighborhood (e.g. 'Kolkata', 'Delhi', 'Whitefield').
        affiliation: School, college, coaching center, or subject (e.g. 'DPS', 'Math tutor').
        identifier: Optional phone number, email, or username to eliminate name collisions.
        save_to_vault: Whether to archive the markdown briefing to ~/.genesis/research/.
    """
    clean_name = name.strip()
    if not clean_name:
        return "Error: Please specify the person's name for due diligence verification."

    loc = location.strip()
    aff = affiliation.strip()
    ident = identifier.strip()

    # 1. Construct Targeted Multi-Pillar Investigative Queries
    queries = {
        "Professional (LinkedIn)": f'site:linkedin.com/in/ "{clean_name}" {loc}'.strip(),
        "Tutoring Portals & Reviews": f'"{clean_name}" {loc} (superprof OR urbanpro OR teacheron OR sulekha OR preply OR tuition)'.strip(),
        "Academic & School Affiliations": f'"{clean_name}" {loc} {aff} (school OR college OR university OR faculty OR coaching)'.strip(),
        "Public Web Footprint": f'"{clean_name}" {loc} {aff}'.strip(),
    }

    if ident:
        queries["Direct Identifier Match"] = f'"{clean_name}" "{ident}"'

    pillar_results: Dict[str, List[Dict[str, str]]] = {}
    seen_urls = set()

    for pillar, q in queries.items():
        out = web_search(q, max_results=3)
        found = re.findall(
            r"### \[(.*?)\]\((https?://[^\)]+)\)\s*- \*\*URL\*\*:\s*`.*?`\s*- \*\*Snippet\*\*:\s*(.*?)(?=\n###|\Z)",
            out,
            re.DOTALL,
        )
        pillar_results[pillar] = []
        for title, url, snippet in found:
            clean_u = url.split("?")[0].strip()
            if clean_u not in seen_urls:
                seen_urls.add(clean_u)
                pillar_results[pillar].append({
                    "title": title.strip(),
                    "url": clean_u,
                    "domain": urllib.parse.urlparse(clean_u).netloc,
                    "snippet": snippet.strip().replace("\n", " "),
                })

    total_sources = sum(len(items) for items in pillar_results.values())

    # 2. Heuristic Confidence & Triangulation Scoring (Scale 1 to 10)
    # Evaluates how strongly we could anchor the identity
    score = 3.0  # Baseline
    has_linkedin = any(
        "linkedin.com" in s["domain"] and clean_name.lower() in s["title"].lower()
        for s in pillar_results.get("Professional (LinkedIn)", [])
    )
    has_tutoring = any(
        any(portal in s["domain"] for portal in ["superprof", "urbanpro", "teacheron", "sulekha", "preply"])
        for s in pillar_results.get("Tutoring Portals & Reviews", [])
    )
    has_academic = any(
        any(w in s["snippet"].lower() for w in ["school", "college", "university", "faculty", "degree", "b.sc", "m.sc", "b.ed"])
        for s in pillar_results.get("Academic & School Affiliations", [])
    )
    has_identifier = bool(ident and pillar_results.get("Direct Identifier Match"))

    if has_linkedin:
        score += 2.0
    if has_tutoring:
        score += 2.0
    if has_academic:
        score += 1.5
    if has_identifier:
        score += 1.5

    # If too few unique sources found, reflect the ambiguity
    if total_sources < 2:
        score = min(score, 3.5)

    final_score = round(max(1.0, min(10.0, score)), 1)

    # 3. Assemble the Due Diligence Briefing
    timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    slug = re.sub(r"[^a-zA-Z0-9_-]", "_", clean_name.lower())
    report_file = RESEARCH_DIR / f"person_{slug}.md"

    briefing = [
        f"# Educator & Due Diligence Briefing: {clean_name}",
        f"*Generated by Project Genesis | Date: {timestamp}*",
        f"**Target Parameters**: Name: `{clean_name}` | Location: `{loc or 'Any'}` | Affiliation: `{aff or 'General'}`\n",
        "---",
        f"## 1. Triangulation & Verification Score: **{final_score} / 10**",
    ]

    if final_score >= 7.0:
        briefing.append(
            "> [!NOTE]\n"
            "> **High Triangulation**: Verified digital anchors found across professional, tutoring, or academic profiles matching this name and location."
        )
    elif final_score >= 4.5:
        briefing.append(
            "> [!IMPORTANT]\n"
            "> **Moderate Triangulation**: Found partial public profiles or mentions, but some identity ambiguity remains. Verify in-person documents."
        )
    else:
        briefing.append(
            "> [!WARNING]\n"
            "> **Low Digital Footprint**: Found few or zero distinct public profiles. This person may be an offline-only tutor or shares a common name."
        )

    briefing.append("\n## 2. Professional & Academic Findings")
    prof_items = pillar_results.get("Professional (LinkedIn)", []) + pillar_results.get("Academic & School Affiliations", [])
    if prof_items:
        for item in prof_items:
            briefing.append(f"- **{item['title']}** (`{item['domain']}`)\n  {item['snippet']}\n  *Link*: [{item['url']}]({item['url']})")
    else:
        briefing.append("- No unambiguous professional or university directory records detected.")

    briefing.append("\n## 3. Tutoring Profiles & Reviews")
    tutor_items = pillar_results.get("Tutoring Portals & Reviews", [])
    if tutor_items:
        for item in tutor_items:
            briefing.append(f"- **{item['title']}** (`{item['domain']}`)\n  {item['snippet']}\n  *Link*: [{item['url']}]({item['url']})")
    else:
        briefing.append("- No registered public profiles found on Superprof, UrbanPro, or TeacherOn.")

    briefing.append("\n## 4. Public Web Mentions & Footprint")
    web_items = pillar_results.get("Public Web Footprint", [])
    if web_items:
        for item in web_items[:3]:
            briefing.append(f"- **{item['title']}**: {item['snippet']}\n  *Link*: [{item['url']}]({item['url']})")
    else:
        briefing.append("- No notable additional public mentions found.")

    briefing.append("\n## 5. Parent Safety & In-Person Verification Checklist")
    briefing.append("Before finalizing any tutoring arrangement or sending your son to their residence, ask these 4 verification questions:")
    briefing.append(f"1. **Photo ID Verification**: Ask to inspect an official government photo ID (Aadhaar / Driver's License) to confirm the legal name matches '{clean_name}'.")
    briefing.append(f"2. **Certificate Check**: Ask to see their highest graduation degree certificate matching what was claimed ({aff or 'their stated degree'}).")
    briefing.append("3. **Parent Reference Check**: Ask for the contact number of one existing or past student's parent you can briefly speak with.")
    briefing.append("4. **First 2 Sessions Protocol**: Host the first two lessons in your home in a common room, rather than sending your child to an unfamiliar residence immediately.")

    final_report = "\n".join(briefing)

    if save_to_vault:
        try:
            report_file.write_text(final_report, encoding="utf-8")
            final_report += f"\n\n---\n*Dossier archived locally to:* `{report_file}`"
        except Exception:
            pass

    return final_report
